using System.Text.Json;
using System.Text.Json.Serialization;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using RequestsManagement.DAL;
using RequestsManagement.DAL.Entities;

namespace RequestsManagement.Tests.Integration;

/// <summary>
/// Hosts the real API in memory against a separate SQL Server (LocalDB) test database.
/// The database is recreated once per test run, so the tests never touch development data.
/// A real SQL Server is used (not EF InMemory) because rowversion and concurrency
/// are generated and enforced by the database itself.
/// </summary>
public class ApiFactory : WebApplicationFactory<Program>, IAsyncLifetime
{
    private const string TestConnectionString =
        "Server=(localdb)\\MSSQLLocalDB;Database=RequestsManagementDb_Tests;Trusted_Connection=True;TrustServerCertificate=True";

    // Same JSON settings as the API (enums as strings, camelCase).
    public static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        Converters = { new JsonStringEnumConverter() }
    };

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        // Not "Development": the development seeding of 100,000 rows does not run.
        builder.UseEnvironment("Testing");

        builder.ConfigureServices(services =>
        {
            // Replace the database registration with the test database.
            services.RemoveAll<DbContextOptions<RequestsDbContext>>();
            services.AddDbContext<RequestsDbContext>(options => options.UseSqlServer(TestConnectionString));
        });
    }

    public async Task InitializeAsync()
    {
        using var scope = Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<RequestsDbContext>();

        await context.Database.EnsureDeletedAsync();
        await context.Database.MigrateAsync();
    }

    Task IAsyncLifetime.DisposeAsync() => Task.CompletedTask;

    public HttpClient CreateApiClient() =>
        CreateClient(new WebApplicationFactoryClientOptions { BaseAddress = new Uri("https://localhost") });

    /// <summary>
    /// Inserts a request directly into the test database and returns it
    /// with the Id and RowVersion generated by SQL Server.
    /// </summary>
    public async Task<Request> AddRequestAsync(
        string organizationName,
        RequestStatus status = RequestStatus.New,
        RequestPriority priority = RequestPriority.Medium,
        string title = "Integration test request")
    {
        using var scope = Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<RequestsDbContext>();

        var now = DateTime.UtcNow;
        var request = new Request
        {
            Title = title,
            OrganizationName = organizationName,
            Status = status,
            Priority = priority,
            CreatedAt = now,
            UpdatedAt = now
        };

        context.Requests.Add(request);
        await context.SaveChangesAsync();

        return request;
    }
}